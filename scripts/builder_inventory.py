#!/usr/bin/env python3
"""What the apps write for themselves that the builder should own (docs/plan/builder-first.md §1).

    scripts/builder_inventory.py <folder of ferrum-app-* checkouts> [--write]

Searches each checkout's committed tree (`git grep` at HEAD, so local edits are not counted) for the
features the builder-first gates take over, and prints docs/builder/inventory.md, or writes it with
`--write`. A search finds where a feature is written, not whether it is right: each row names the
pattern it used, so a count can be checked by hand. Private repositories are left out.
"""

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "builder" / "inventory.md"
PRIVATE = {"ferrum-app-cloud"}

# (key, what it is, the gate that takes it over, extended regular expression, paths searched)
PATTERNS = [
    ("site", "Pages or endpoints served by the app's own handler", "BF1, BF2", r"impl[[:space:]]+([a-z_]+::)*Site[[:space:]]+for", ["src"]),
    ("portal", "A page of the workspace's portal", "BF1", r"^[[:space:]]*shell\.portal:", ["app.yaml"]),
    ("guest_links", "A guest's own link, hashed and checked by the app", "BF2", r"token_hash|digest\(token", ["src"]),
    ("approvals", "Approval decisions written in the app", "BF3", r"[Aa]pprov[a-z_]*.*(Error::|Forbidden|refuse)|(Error::|Forbidden).*[Aa]pprov|fn [a-z_]*approv[a-z_]*\(", ["src"]),
    ("independence", "\"Someone other than whoever did it\" checks", "BF3", r"[Ss]omeone other than|other than who|!= *ctx\.user|ctx\.user *!=", ["src"]),
    ("invoices", "ERP invoices made or read by name", "BF4", r"\"(SalesInvoice|PurchaseInvoice)\"", ["src"]),
    ("journals", "Journal entries posted by the app", "BF4", r"\"JournalEntry\"", ["src"]),
    ("upkeep", "A scheduled upkeep loop that does something", "BF6", r"fn maintenance(_at)?\((k|kernel)[,:)]", ["src"]),
    ("mail", "Mail queued by the app's code", "BF6", r"queue_mail\(", ["src"]),
    ("reports", "Report sources of the app's own", "BF7", r"impl[[:space:]]+([a-z_]+::)*ReportSource[[:space:]]+for", ["src"]),
]


def grep(repo: Path, pattern: str, paths: list) -> list:
    run = subprocess.run(["git", "-C", str(repo), "grep", "-n", "-E", pattern, "HEAD", "--", *paths], capture_output=True, text=True)
    if run.returncode not in (0, 1):
        raise SystemExit(f"{repo.name}: git grep failed: {run.stderr.strip()}")
    # "HEAD:src/site.rs:12:impl Site for ..." -> ("src/site.rs", 12)
    hits = []
    for line in run.stdout.splitlines():
        _, path, number, _ = line.split(":", 3)
        hits.append((path, int(number)))
    return hits


def main() -> int:
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    if len(args) != 1:
        print(__doc__, file=sys.stderr)
        return 2
    folder = Path(args[0]).resolve()
    repos = sorted(p for p in folder.iterdir() if p.name.startswith("ferrum-app-") and (p / ".git").exists() and p.name not in PRIVATE)
    heads = {r.name: subprocess.run(["git", "-C", str(r), "rev-parse", "--short", "HEAD"], capture_output=True, text=True, check=True).stdout.strip() for r in repos}
    found = {key: {} for key, *_ in PATTERNS}
    for repo in repos:
        for key, _, _, pattern, paths in PATTERNS:
            hits = grep(repo, pattern, paths)
            if hits:
                found[key][repo.name] = hits
    out = [
        "# What the apps write for themselves",
        "",
        "Generated by `scripts/builder_inventory.py`; run it again rather than editing this. It searched the committed",
        f"tree of {len(repos)} app repositories (private ones left out) for the features the builder-first gates take over",
        "([docs/plan/builder-first.md](../plan/builder-first.md)). A search finds where a feature is written, not",
        "whether it is right; each row names its pattern.",
        "",
        "| Feature | Gate | Apps | Pattern |",
        "|---|---|---|---|",
    ]
    for key, label, gate, pattern, paths in PATTERNS:
        shown = pattern.replace("|", "\\|").replace("[[:space:]]", "\\s")
        out.append(f"| {label} | {gate} | {len(found[key])} | `{shown}` in {', '.join(paths)} |")
    out += ["", "## Where", ""]
    for key, label, gate, _, _ in PATTERNS:
        out += [f"### {label} ({gate})", ""]
        if not found[key]:
            out += ["None.", ""]
            continue
        for app, hits in sorted(found[key].items()):
            places = ", ".join(f"`{path}:{line}`" for path, line in hits[:6]) + (f" and {len(hits) - 6} more" if len(hits) > 6 else "")
            out.append(f"* {app.removeprefix('ferrum-app-')}: {places}")
        out.append("")
    out += ["## Heads searched", "", " · ".join(f"{name.removeprefix('ferrum-app-')} {head}" for name, head in heads.items()), ""]
    text = "\n".join(out)
    if "--write" in sys.argv:
        OUT.parent.mkdir(parents=True, exist_ok=True)
        OUT.write_text(text)
        print(f"wrote {OUT.relative_to(ROOT)}: " + ", ".join(f"{key} {len(found[key])}" for key, *_ in PATTERNS))
    else:
        print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
