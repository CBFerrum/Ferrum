#!/usr/bin/env python3
"""The settings' registry (server/src/settings.yaml; docs/plan/stateless.md, D2) against what reads them.

    scripts/settings.py            # check; exit 1 on any finding
    scripts/settings.py --write    # write the operations guide's table from the registry, then check

What it checks:
* every `get_env(name=...)` in server/config/*.yaml names a variable the registry declares, or one of the boot
  contract (DATABASE_URL);
* each declared `path` is where config/production.yaml reads that variable;
* every variable the Rust code in server/ and crates/ names to read (`std::env::var("X")`, `ferrum_kernel::env::var`,
  and the readers' own `env("X")`, `var("X")`, `some("X")`, `set("X")`, `env!`, `option_env!`) is declared, or on the
  allow-list below: the boot contract, tests' own, and what the build bakes in;
* the registry itself: each key and variable once, a known type, a choice with its values, a secret neither stored nor
  live, a vault's kind only on a secret, and the three settings a pool has of its own;
* the table in docs/operations.md between its markers is the one this registry makes.
"""

import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
REGISTRY = ROOT / "server/src/settings.yaml"
CONFIGS = sorted((ROOT / "server/config").glob("*.yaml"))
GUIDE = ROOT / "docs/operations.md"
BEGIN = "<!-- settings: generated by scripts/settings.py from server/src/settings.yaml; do not edit by hand -->"
END = "<!-- settings: end -->"

# Read from the environment, and rightly not settings.
ALLOWED = {
    "DATABASE_URL": "the boot contract (D1)",
    "FERRUM_BUILD_DATE": "baked in by the build (window.rs)",
    "FERRUM_XMLSEC_VERSION": "baked in by the build (crates/saml)",
    "BUILD_SHA": "baked in by the build",
    "GITHUB_SHA": "baked in by the build",
    "OUT_DIR": "build scripts",
    "FERRUM_EXPORT_SAMPLES": "a test's sample files (crates/kernel/src/coedit.rs)",
    "FERRUM_DOCX_SAMPLE": "a test's sample files (crates/kernel/src/coedit/docx.rs)",
    "FERRUM_DOCX_COMMENTS": "a test's sample files (crates/kernel/src/coedit/docx.rs)",
    "FERRUM_PARITY_STATES": "a test's sample files (crates/kernel/src/coedit/docx.rs)",
    "FERRUM_PARITY_OUT": "a test's sample files (crates/kernel/src/coedit/docx.rs)",
    # A machine's own identity, which the S3 library reads; the server only asks whether one is named
    # (server/src/objects.rs, `IDENTITY`).
    "AWS_WEB_IDENTITY_TOKEN_FILE": "a machine's identity for the object store (IRSA)",
    "AWS_CONTAINER_CREDENTIALS_FULL_URI": "a machine's identity for the object store (EKS Pod Identity, ECS)",
    "AWS_CONTAINER_CREDENTIALS_RELATIVE_URI": "a machine's identity for the object store (ECS)",
}
TEST_NAME = re.compile(r"(^|_)TEST(_|$)|^CARGO_")
READ = re.compile(r"(?:env::var|env::var_os|\benv|\bvar|\bsome|\bset|option_env!|\benv!)\(\s*\"([A-Z][A-Z0-9_]{2,})\"")
GET_ENV = re.compile(r'get_env\(name="([A-Z0-9_]+)"')
# A whole `<%= get_env(...) %>` tag, so that a file can be read as YAML with each tag in its variable's place.
TAG = re.compile(r'<%=\s*get_env\(name="([A-Z0-9_]+)"(?:,\s*default="(?:[^"\\]|\\.)*")?\)\s*%>')
TYPES = {"text", "bool", "int", "json", "choice"}
# How the vault holds a platform secret (server/src/secrets.rs).
HELD = {"session", "compared", "library"}
POOL = ["db_max_connections", "run_background", "zone"]


def registry():
    entries = yaml.safe_load(REGISTRY.read_text())
    return entries if isinstance(entries, list) else []


def registry_findings(entries):
    found = []
    keys, envs = set(), set()
    for e in entries:
        key, env = e.get("key"), e.get("env")
        where = key or env or "an entry"
        if not key or not env or not str(e.get("doc", "")).strip():
            found.append(f"{where}: key, env and doc are required")
        if key in keys or env in envs:
            found.append(f"{where}: declared twice")
        keys.add(key)
        envs.add(env)
        kind = e.get("type", "text")
        if kind not in TYPES:
            found.append(f"{where}: type {kind!r} is not one of {sorted(TYPES)}")
        if (kind == "choice") != bool(e.get("values")):
            found.append(f"{where}: a choice has values, and only a choice")
        if not isinstance(e.get("default", ""), str) or any(not isinstance(v, str) for v in e.get("values", [])):
            found.append(f"{where}: defaults and values are quoted text")
        if e.get("secret") and e.get("environment"):
            found.append(f"{where}: a secret, or read from the environment by someone else, not both")
        if (e.get("secret") or e.get("environment")) and (e.get("applies") == "live" or e.get("scope") == "pool"):
            found.append(f"{where}: only what the table holds applies at once or per pool")
        if e.get("sends") and not any(x.get("env") == e["sends"] and x.get("secret") for x in entries):
            found.append(f"{where}: sends {e['sends']}, which is not a secret of the registry")
        if e.get("vault") is not None and (not e.get("secret") or e["vault"] not in HELD):
            found.append(f"{where}: vault is one of {sorted(HELD)}, and only on a secret")
    pools = [e.get("key") for e in entries if e.get("scope") == "pool"]
    if pools != POOL:
        found.append(f"a pool's own settings are {POOL}, not {pools}")
    return found


def config_paths(path):
    """Each `get_env` variable of a configuration file, and the dotted paths it is read at."""
    out = {}

    def walk(node, at):
        if isinstance(node, dict):
            for k, v in node.items():
                walk(v, f"{at}.{k}" if at else str(k))
        elif isinstance(node, list):
            for v in node:
                walk(v, at)
        elif isinstance(node, str):
            for name in re.findall(r"ENVVAR_([A-Z0-9_]+?)_ENVVAR", node):
                out.setdefault(name, set()).add(at)

    walk(yaml.safe_load(TAG.sub(lambda m: f"ENVVAR_{m.group(1)}_ENVVAR", path.read_text())), "")
    return out


def config_findings(entries):
    found = []
    declared = {e["env"]: e for e in entries if e.get("env")}
    for path in CONFIGS:
        for name in GET_ENV.findall(path.read_text()):
            if name not in declared and name not in ALLOWED:
                found.append(f"{path.relative_to(ROOT)}: {name} is read here but not declared in {REGISTRY.relative_to(ROOT)}")
    production = config_paths(ROOT / "server/config/production.yaml")
    for name, at in production.items():
        e = declared.get(name)
        if e is not None and e.get("path") not in at:
            found.append(f"{e['key']}: config/production.yaml reads {name} at {', '.join(sorted(at))}, the registry says {e.get('path')}")
    for e in entries:
        if e.get("path") and e["path"] not in production.get(e["env"], set()):
            found.append(f"{e['key']}: its path {e['path']} is not where config/production.yaml reads {e['env']}")
    return found


def code_findings(entries):
    found = []
    declared = {e["env"] for e in entries if e.get("env")}
    for base in ("server", "crates"):
        for f in sorted((ROOT / base).rglob("*.rs")):
            rel = f.relative_to(ROOT)
            if "/tests/" in f"/{rel}" or f.name == "build.rs" or "target" in rel.parts:
                continue
            for n, line in enumerate(f.read_text(errors="ignore").splitlines(), 1):
                for name in READ.findall(line):
                    if name in declared or name in ALLOWED or TEST_NAME.search(name):
                        continue
                    found.append(f"{rel}:{n}: reads {name}, which {REGISTRY.relative_to(ROOT)} does not declare")
    return found


def cell(text):
    return " ".join(str(text).split()).replace("|", "\\|")


def table(entries):
    rows = [
        "| Setting | Variable | Type | Default | Where it lives | Meaning |",
        "|---|---|---|---|---|---|",
    ]
    for e in entries:
        kind = e.get("type", "text")
        if kind == "choice":
            kind = ", ".join(f"`{v}`" if v else "empty" for v in e["values"])
        default = e.get("default", "")
        if e.get("secret") and e.get("vault"):
            where = f"secret: the environment, else the vault ({e['vault']})"
        elif e.get("secret"):
            where = "secret: the environment"
        elif e.get("environment"):
            where = f"the environment ({e['environment'].split(',')[0]})"
        else:
            when = "at once" if e.get("applies") == "live" else "next start"
            where = f"{'each pool' if e.get('scope') == 'pool' else 'installation'}, {when}"
            if e.get("sends"):
                where += f"; not from the table while `{e['sends']}` is in the environment; moving it takes that secret again or clears it"
        rows.append(f"| `{e['key']}` | `{e['env']}` | {kind} | {f'`{cell(default)}`' if default else ''} | {where} | {cell(e.get('doc', ''))} |")
    return "\n".join(rows)


def guide_findings(entries, write):
    text = GUIDE.read_text()
    if BEGIN not in text or END not in text:
        return [f"{GUIDE.relative_to(ROOT)} has no settings table between its markers"]
    head, rest = text.split(BEGIN, 1)
    old, tail = rest.split(END, 1)
    new = f"\n{table(entries)}\n"
    if old == new:
        return []
    if write:
        GUIDE.write_text(head + BEGIN + new + END + tail)
        return []
    return [f"{GUIDE.relative_to(ROOT)}: the settings table is not the registry's; run python3 scripts/settings.py --write"]


def main():
    write = "--write" in sys.argv[1:]
    entries = registry()
    found = registry_findings(entries) + config_findings(entries) + code_findings(entries) + guide_findings(entries, write)
    for f in found:
        print(f)
    live = sum(1 for e in entries if e.get("applies") == "live")
    secret = sum(1 for e in entries if e.get("secret"))
    held = sum(1 for e in entries if e.get("vault"))
    elsewhere = sum(1 for e in entries if e.get("environment"))
    print(f"{len(entries)} settings: {live} apply at once, {secret} secrets ({held} in the vault), {elsewhere} read from the environment by others; {len(found)} findings")
    return 1 if found else 0


if __name__ == "__main__":
    sys.exit(main())
